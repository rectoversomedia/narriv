"""Generate app/dark.css: dark-mode overrides for every color utility the app uses (run after adding colors).
Light surfaces become dark ones, dark text becomes light, pastel tints become deep tints of the same hue,
saturated brand/status colors stay. Applied under html.dark (set from Settings, dashboard only)."""
import re, os, colorsys, glob
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAMED = {"white": "#FFFFFF", "black": "#000000", "slate-50": "#F8FAFC", "slate-100": "#F1F5F9", "slate-200": "#E2E8F0", "slate-300": "#CBD5E1", "slate-400": "#94A3B8", "slate-500": "#64748B", "slate-600": "#475569", "slate-700": "#334155", "slate-800": "#1E293B", "slate-900": "#0F172A", "slate-950": "#020617", "gray-50": "#F9FAFB", "gray-100": "#F3F4F6", "gray-200": "#E5E7EB", "gray-500": "#6B7280", "gray-600": "#4B5563", "gray-700": "#374151", "gray-900": "#111827", "navy": "#101334"}
files = [f for g in ("app/**/*.tsx", "components/**/*.tsx", "lib/**/*.ts") for f in glob.glob(os.path.join(ROOT, g), recursive=True)]
files = [f for f in files if "/marketing/" not in f and "/(marketing)/" not in f]
pat = re.compile(r"(?<![\w-])((?:hover:|focus:|focus-within:|group-hover:|disabled:|active:)?)(bg|text|border|border-t|border-b|border-l|border-r|ring|divide|fill|stroke|outline|placeholder:text)-(\[#[0-9A-Fa-f]{3,8}\]|white|black|navy|(?:slate|gray)-\d{2,3})(/\d{1,3})?(?![\w\[-])")
found = set()
for f in files:
    for m in pat.finditer(open(f, encoding="utf8").read()):
        found.add(tuple(x or "" for x in m.groups()))

def hexrgb(h):
    h = h.lstrip("#")
    if len(h) == 3: h = "".join(c * 2 for c in h)
    return tuple(int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))

def tohex(r, g, b):
    return "#%02X%02X%02X" % tuple(round(max(0, min(1, v)) * 255) for v in (r, g, b))

def transform(hexc, prop):
    r, g, b = hexrgb(hexc)
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    if s < 0.25 or l > 0.97: h = 0.64  # neutrals take Narriv's navy hue, not a stray red from pure white
    if prop in ("bg", "fill"):
        if l >= 0.96 and s < 0.6: l, s = 0.13, 0.38           # white / near-white surface
        elif l >= 0.9: l, s = 0.17, min(s, 0.45)                # soft surface / pastel tint
        elif l >= 0.8: l, s = 0.22, min(s, 0.5)
        elif l < 0.16: l, s = 0.24, min(s, 0.45)                                # ink buttons stay visible on dark
        elif l < 0.3 and s < 0.5: l = 0.30
        else: return None                                        # brand and status colors stay
    elif prop in ("text", "placeholder:text", "stroke"):
        if l < 0.2: l, s = 0.93, min(s, 0.25)                     # ink text
        elif s < 0.4 and l < 0.7: l = min(0.9, 0.42 + l * 0.65)  # greys
        elif l < 0.55: l = 0.72                                  # dark colored text (red, green, blue)
        elif l >= 0.95: return None                              # white text stays
        else: return None
    else:  # borders, rings, dividers, outlines
        if l >= 0.8: l, s = 0.25, min(s, 0.35)
        elif l < 0.16: l, s = 0.42, 0.3                         # ink borders of the tactile cards
        else: return None
    return tohex(*colorsys.hls_to_rgb(h, l, s))

CSSPROP = {"bg": ["background-color"], "fill": ["fill"], "text": ["color"], "placeholder:text": ["color"], "stroke": ["stroke"], "border": ["border-color"], "border-t": ["border-top-color"], "border-b": ["border-bottom-color"], "border-l": ["border-left-color"], "border-r": ["border-right-color"], "ring": ["--tw-ring-color"], "divide": ["border-color"], "outline": ["outline-color"]}
PSEUDO = {"": "", "hover:": ":hover", "focus:": ":focus", "focus-within:": ":focus-within", "disabled:": ":disabled", "active:": ":active", "group-hover:": ""}

def esc(cls):
    return re.sub(r"([\[\]#/:.%()])", r"\\\1", cls)

rules = []
for prefix, prop, val, alpha in sorted(found):
    hexc = NAMED.get(val) or val[1:-1]
    new = transform(hexc, prop)
    if not new: continue
    cls = f"{prefix}{prop}-{val}{alpha or ''}"
    a = int(alpha[1:]) / 100 if alpha else None
    color = new if a is None else "rgb(%d %d %d / %s)" % (*(round(v * 255) for v in hexrgb(new)), a)
    sel = f".{esc(cls)}"
    if prefix == "group-hover:": sel = f".group:hover {sel}"
    elif prefix == "placeholder:" or prop == "placeholder:text": sel = f"{sel}::placeholder"
    else: sel += PSEUDO[prefix]
    if prop == "divide": sel += " > :not([hidden]) ~ :not([hidden])"
    decl = "; ".join(f"{p}: {color}" for p in CSSPROP[prop])
    rules.append(f"html.dark {sel} {{ {decl} }}")

head = "/* Generated by scripts/gen-dark-css.py: do not edit by hand. */\n"
open(os.path.join(ROOT, "app/dark.css"), "w").write(head + "\n".join(rules) + "\n")
print(len(rules), "rules")
